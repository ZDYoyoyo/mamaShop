-- =====================================================================
-- V1：初始 Schema
-- 原則：
--   * 主鍵用 BIGINT IDENTITY（PostgreSQL 標準寫法，取代 SERIAL）
--   * 時間一律用 TIMESTAMPTZ（帶時區），避免主機時區不同造成時間錯亂
--   * 金額一律 NUMERIC(10,2)
--   * Enum 存字串（對應 JPA 的 EnumType.STRING），用 CHECK 限制可用的值
--   * updated_at 由 JPA 維護（B03），不使用資料庫 trigger
-- 已執行過的 migration 不能再修改；要改 schema 請新增 V2、V3…
-- =====================================================================

-- ---------------------------------------------------------------------
-- 會員（顧客與管理員共用）
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255) NOT NULL,          -- 應用程式統一轉小寫後再存
    password_hash   VARCHAR(100) NOT NULL,          -- BCrypt 雜湊（60 字元），不存明碼
    name            VARCHAR(50)  NOT NULL,
    phone           VARCHAR(20),
    role            VARCHAR(20)  NOT NULL DEFAULT 'USER',
    enabled         BOOLEAN      NOT NULL DEFAULT TRUE,  -- 停用帳號而不刪除，保留操作紀錄
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role  CHECK (role IN ('USER', 'ADMIN'))
);

-- ---------------------------------------------------------------------
-- 商品分類
-- ---------------------------------------------------------------------
CREATE TABLE categories (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(50) NOT NULL,
    sort_order      INT         NOT NULL DEFAULT 0,
    CONSTRAINT uk_categories_name UNIQUE (name)
);

-- ---------------------------------------------------------------------
-- 商品（無規格：顏色、尺寸不同就是不同商品）
-- 商品不做實體刪除，下架用 status = OFF_SALE，
-- 因為舊訂單明細的 product_id 還會參照它
-- ---------------------------------------------------------------------
CREATE TABLE products (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id     BIGINT        NOT NULL,
    name            VARCHAR(100)  NOT NULL,
    description     TEXT,
    price           NUMERIC(10,2) NOT NULL,
    stock           INT           NOT NULL DEFAULT 0,
    image_path      VARCHAR(255),
    status          VARCHAR(20)   NOT NULL DEFAULT 'OFF_SALE',  -- 新商品預設下架，確認無誤再上架
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT ck_products_price    CHECK (price >= 0),
    CONSTRAINT ck_products_stock    CHECK (stock >= 0),            -- 最後一道防線：就算程式有 bug 也不會超賣
    CONSTRAINT ck_products_status   CHECK (status IN ('ON_SALE', 'OFF_SALE'))
);

-- 前台商品列表：依分類、只撈上架中
CREATE INDEX idx_products_category_status ON products (category_id, status);

-- ---------------------------------------------------------------------
-- 運送方式與運費（後台可調整）
-- ---------------------------------------------------------------------
CREATE TABLE shipping_methods (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(20)   NOT NULL,
    name            VARCHAR(50)   NOT NULL,
    fee             NUMERIC(10,2) NOT NULL,
    enabled         BOOLEAN       NOT NULL DEFAULT TRUE,
    sort_order      INT           NOT NULL DEFAULT 0,
    CONSTRAINT uk_shipping_methods_code UNIQUE (code),
    CONSTRAINT ck_shipping_methods_code CHECK (code IN ('HOME_DELIVERY', 'CVS_PICKUP')),
    CONSTRAINT ck_shipping_methods_fee  CHECK (fee >= 0)
);

-- 運送方式是系統運作必需的資料（不是測試資料），正式環境也要有，所以放在 V1。
-- 運費先填預設值，上線前由家人在後台調整。
INSERT INTO shipping_methods (code, name, fee, enabled, sort_order) VALUES
    ('HOME_DELIVERY', '宅配',     100.00, TRUE, 1),
    ('CVS_PICKUP',    '超商取貨',  60.00, TRUE, 2);

-- ---------------------------------------------------------------------
-- 訂單
-- ---------------------------------------------------------------------
CREATE TABLE orders (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_no            VARCHAR(32)   NOT NULL,
    user_id             BIGINT        NOT NULL,

    -- 金額（下單當下計算並保存，之後商品改價、運費調整都不影響）
    items_amount        NUMERIC(10,2) NOT NULL,
    shipping_fee        NUMERIC(10,2) NOT NULL,
    total_amount        NUMERIC(10,2) NOT NULL,

    -- 收件資訊
    recipient_name      VARCHAR(50)   NOT NULL,
    recipient_phone     VARCHAR(20)   NOT NULL,
    note                VARCHAR(500),

    -- 運送：宅配填地址；超商取貨填門市（第 1 階段顧客手動填寫）
    shipping_method     VARCHAR(20)   NOT NULL,
    shipping_address    VARCHAR(255),
    cvs_brand           VARCHAR(10),
    cvs_store_code      VARCHAR(20),
    cvs_store_name      VARCHAR(50),
    tracking_no         VARCHAR(50),

    -- 付款與狀態
    payment_method      VARCHAR(20)   NOT NULL DEFAULT 'COD',
    payment_status      VARCHAR(20)   NOT NULL DEFAULT 'UNPAID',
    status              VARCHAR(20)   NOT NULL,

    -- 樂觀鎖（JPA @Version）：兩位管理員同時改同一張訂單時，後送出的會失敗
    version             BIGINT        NOT NULL DEFAULT 0,

    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    confirmed_at        TIMESTAMPTZ,
    shipped_at          TIMESTAMPTZ,
    delivered_at        TIMESTAMPTZ,
    completed_at        TIMESTAMPTZ,
    cancelled_at        TIMESTAMPTZ,
    returned_at         TIMESTAMPTZ,
    paid_at             TIMESTAMPTZ,

    CONSTRAINT uk_orders_order_no UNIQUE (order_no),
    CONSTRAINT fk_orders_user     FOREIGN KEY (user_id) REFERENCES users (id),

    CONSTRAINT ck_orders_amounts  CHECK (
        items_amount >= 0 AND shipping_fee >= 0
        AND total_amount = items_amount + shipping_fee
    ),
    CONSTRAINT ck_orders_shipping_method CHECK (shipping_method IN ('HOME_DELIVERY', 'CVS_PICKUP')),
    CONSTRAINT ck_orders_cvs_brand       CHECK (cvs_brand IN ('SEVEN', 'FAMILY', 'HILIFE', 'OK')),
    -- 依運送方式，必填的收件欄位不同
    CONSTRAINT ck_orders_shipping_info   CHECK (
        (shipping_method = 'HOME_DELIVERY' AND shipping_address IS NOT NULL)
        OR
        (shipping_method = 'CVS_PICKUP' AND cvs_brand IS NOT NULL
            AND cvs_store_code IS NOT NULL AND cvs_store_name IS NOT NULL)
    ),
    CONSTRAINT ck_orders_payment_method  CHECK (payment_method IN ('COD')),  -- 接金流（P01）時再加 ONLINE
    CONSTRAINT ck_orders_payment_status  CHECK (payment_status IN ('UNPAID', 'PAID', 'REFUNDED')),
    CONSTRAINT ck_orders_status          CHECK (status IN (
        'PENDING_PAYMENT', 'PENDING_CONFIRM', 'PROCESSING', 'SHIPPED',
        'DELIVERED', 'COMPLETED', 'CANCELLED', 'RETURNED'
    ))
);

-- 顧客「我的訂單」：依會員、新到舊
CREATE INDEX idx_orders_user_created   ON orders (user_id, created_at DESC);
-- 後台訂單列表：依狀態篩選、新到舊
CREATE INDEX idx_orders_status_created ON orders (status, created_at DESC);

-- ---------------------------------------------------------------------
-- 訂單明細（商品名稱、單價是下單當下的快照）
-- ---------------------------------------------------------------------
CREATE TABLE order_items (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT        NOT NULL,
    product_id      BIGINT        NOT NULL,
    product_name    VARCHAR(100)  NOT NULL,
    unit_price      NUMERIC(10,2) NOT NULL,
    quantity        INT           NOT NULL,
    subtotal        NUMERIC(10,2) NOT NULL,
    CONSTRAINT fk_order_items_order    FOREIGN KEY (order_id)   REFERENCES orders (id),
    CONSTRAINT fk_order_items_product  FOREIGN KEY (product_id) REFERENCES products (id),
    -- 同一張訂單裡同一個商品只出現一筆（數量合併）
    CONSTRAINT uk_order_items_order_product UNIQUE (order_id, product_id),
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_items_subtotal CHECK (unit_price >= 0 AND subtotal = unit_price * quantity)
);
-- 註：uk_order_items_order_product 的索引以 order_id 開頭，查某張訂單的明細可以直接用，不用另外建索引

-- ---------------------------------------------------------------------
-- 訂單狀態變更紀錄（誰、在什麼時候、從什麼狀態改成什麼狀態）
-- ---------------------------------------------------------------------
CREATE TABLE order_status_histories (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        BIGINT       NOT NULL,
    from_status     VARCHAR(20),                     -- 建立訂單的第一筆為 NULL
    to_status       VARCHAR(20)  NOT NULL,
    operator_id     BIGINT,                          -- 顧客或管理員；系統自動處理時為 NULL
    note            VARCHAR(255),
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_order_status_histories_order    FOREIGN KEY (order_id)    REFERENCES orders (id),
    CONSTRAINT fk_order_status_histories_operator FOREIGN KEY (operator_id) REFERENCES users (id)
);

CREATE INDEX idx_order_status_histories_order ON order_status_histories (order_id, created_at);
