-- V2：記錄密碼最後修改時間（B14）
--
-- 用途：重設密碼後，讓「在這之前發出的 JWT」全部失效。
-- JWT 是無狀態的，伺服器不記錄發出過哪些 token；
-- 所以改成比對 token 的發行時間（iat）是否早於密碼修改時間，早於就拒絕。
--
-- 既有資料為 NULL（代表從沒改過密碼，不影響現有 token）。
-- 注意：V1 已經執行過，不能修改 V1，schema 變更一律新增檔案。
-- =====================================================================

ALTER TABLE users ADD COLUMN password_changed_at TIMESTAMPTZ;
